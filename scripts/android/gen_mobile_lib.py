# -*- coding: utf-8 -*-
"""Generate scripts/android/overlay/lib.rs from the invoke() command names used
by the SvelteKit frontend.

The desktop Rust crate pulls in single-instance, tray, librqbit, X11/ONNX/SQLite
and native-tls dependencies that cannot compile for aarch64-linux-android.
The Android build therefore keeps the original frontend and swaps in a minimal
Tauri runtime that registers safe no-op stubs for every command, so the UI can
render instead of failing with "command not found".

Re-run after adding new commands:  python scripts/android/gen_mobile_lib.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
CMDS = ROOT / "scripts" / "android" / "cmds.txt"
OUT = ROOT / "scripts" / "android" / "overlay" / "lib.rs"

KEYWORDS = {
    "as", "break", "const", "continue", "crate", "else", "enum", "extern",
    "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod",
    "move", "mut", "pub", "ref", "return", "self", "static", "struct", "super",
    "trait", "true", "type", "unsafe", "use", "where", "while", "async", "await",
    "dyn", "abstract", "become", "box", "do", "final", "macro", "override",
    "priv", "typeof", "unsized", "virtual", "yield", "try", "union",
}

names = []
for line in CMDS.read_text(encoding="utf-8").splitlines():
    n = line.strip()
    if not re.fullmatch(r"[a-z][a-z0-9_]{1,59}", n):
        continue
    if n in KEYWORDS:
        continue
    names.append(n)
names = sorted(set(names))


def body(name):
    if "version" in name:
        return 'serde_json::json!("0.16.6-android")'
    if name.startswith(("get_", "load_", "list_", "fetch_", "prefetch_",
                        "check_", "query_", "read_", "resolve_")):
        return "serde_json::json!({})"
    if name.startswith(("mark_", "save_", "set_", "clear_", "remove_",
                        "update_", "install_", "pause_", "resume_", "retry_",
                        "cancel_", "add_", "delete_", "enable_", "disable_")):
        return "serde_json::json!(true)"
    return "serde_json::Value::Null"


out = [
    "// AUTO-GENERATED by scripts/android/gen_mobile_lib.py -- do not edit by hand.",
    "//",
    "// OmniGet Android runtime. The desktop crate depends on yt-dlp/FFmpeg",
    "// binaries plus single-instance / tray / librqbit / X11 / ONNX / native-tls",
    "// crates that cannot build for aarch64-linux-android. This build keeps the",
    "// full SvelteKit UI and registers no-op stubs so the interface renders.",
    "// Downloading is intentionally disabled; see docs in the workflow.",
    "",
    "#[cfg_attr(mobile, tauri::mobile_entry_point)]",
    "pub fn run() {",
    "    tauri::Builder::default()",
    "        .invoke_handler(tauri::generate_handler![",
]
for n in names:
    out.append(f"            {n},")
out += [
    "        ])",
    "        .run(tauri::generate_context!())",
    '        .expect("failed to launch OmniGet Android");',
    "}",
    "",
]
for n in names:
    out += [
        "#[tauri::command]",
        f"fn {n}() -> serde_json::Value {{ {body(n)} }}",
        "",
    ]
OUT.write_text("\n".join(out), encoding="utf-8")
print(f"generated {len(names)} stubs -> {OUT}")
